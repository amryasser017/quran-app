const khatmDua = `اللَّهُمَّ ارْحَمْنِي بِالْقُرْآنِ، وَاجْعَلْهُ لِي إِمَامًا وَنُورًا وَهُدًى وَرَحْمَةً،
اللَّهُمَّ ذَكِّرْنِي مِنْهُ مَا نُسِّيتُ، وَعَلِّمْنِي مِنْهُ مَا جَهِلْتُ، وَارْزُقْنِي تِلَاوَتَهُ آنَاءَ اللَّيْلِ وَأَطْرَافَ النَّهَارِ، وَاجْعَلْهُ لِي حُجَّةً يَا رَبَّ الْعَالَمِينَ.

اللَّهُمَّ اجْعَلِ الْقُرْآنَ الْعَظِيمَ رَبِيعَ قُلُوبِنَا، وَنُورَ صُدُورِنَا، وَجَلَاءَ أَحْزَانِنَا، وَذَهَابَ هُمُومِنَا وَغُمُومِنَا.

اللَّهُمَّ إِنَّا نَسْأَلُكَ بِأَنَّ لَكَ الْحَمْدَ لَا إِلَهَ إِلَّا أَنْتَ الْمَنَّانُ بَدِيعَ السَّمَاوَاتِ وَالْأَرْضِ ذَا الْجَلَالِ وَالْإِكْرَامِ أَنْ تَجْعَلَ الْقُرْآنَ الْعَظِيمَ رَبِيعَ قُلُوبِنَا وَنُورَ صُدُورِنَا، وَجِلَاءَ أَحْزَانِنَا، وَذَهَابَ هُمُومِنَا.

اللَّهُمَّ اجْعَلْنَا مِمَّنْ يَتْلُو كِتَابَكَ حَقَّ تِلَاوَتِهِ، وَيَتَدَبَّرُ آيَاتِهِ، وَيَعْمَلُ بِمَا فِيهِ مِنْ أَمْرٍ وَنَهْيٍ.

اللَّهُمَّ تَقَبَّلْ مِنَّا هَذَا الْخَتْمَ، وَاجْعَلْهُ خَالِصًا لِوَجْهِكَ الْكَرِيمِ، وَاجْمَعْ بِهِ شَمْلَنَا، وَاغْفِرْ بِهِ ذَنْبَنَا، وَارْحَمْ بِهِ ضَعْفَنَا، وَيَسِّرْ بِهِ أَمْرَنَا.

اللَّهُمَّ صَلِّ وَسَلِّمْ وَبَارِكْ عَلَى سَيِّدِنَا مُحَمَّدٍ وَعَلَى آلِهِ وَصَحْبِهِ أَجْمَعِينَ، وَالْحَمْدُ لِلَّهِ رَبِّ الْعَالَمِينَ.`

